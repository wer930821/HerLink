begin;

create table if not exists public.anonymous_identity_binding_history (
  id bigint generated by default as identity primary key,
  anonymous_identity_id uuid not null references public.profiles(id) on delete cascade,
  active_auth_user_id uuid not null references auth.users(id) on delete cascade,
  generation bigint not null,
  source text not null default 'identity_claim',
  created_at timestamptz not null default timezone('utc'::text, now())
);
create index if not exists anonymous_identity_binding_history_auth_idx
  on public.anonymous_identity_binding_history(active_auth_user_id, created_at desc);
create index if not exists anonymous_identity_binding_history_identity_idx
  on public.anonymous_identity_binding_history(anonymous_identity_id, created_at desc);
alter table public.anonymous_identity_binding_history enable row level security;
revoke all on table public.anonymous_identity_binding_history from public, anon, authenticated;
grant all on table public.anonymous_identity_binding_history to service_role;

create or replace function public.claim_anonymous_identity_device(p_identity_id uuid,p_new_auth_user_id uuid)
returns table (anonymous_identity_id uuid, active_auth_user_id uuid, generation bigint)
language plpgsql security definer set search_path=public,pg_temp as $$
declare v_state public.anonymous_identity_device_state%rowtype;
begin
  if not exists(select 1 from public.profiles where id=p_identity_id and anonymous_mode_enabled=true) then raise exception 'ANONYMOUS_IDENTITY_NOT_FOUND'; end if;
  if not exists(select 1 from public.profiles where id=p_new_auth_user_id and anonymous_mode_enabled=true) then raise exception 'REPLACEMENT_ANONYMOUS_PROFILE_NOT_FOUND'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_identity_id::text,0));
  perform pg_advisory_xact_lock(hashtextextended(p_new_auth_user_id::text,0));
  if exists(select 1 from public.anonymous_identity_device_state where active_auth_user_id=p_new_auth_user_id and anonymous_identity_id<>p_identity_id) then raise exception 'AUTH_USER_ALREADY_BOUND'; end if;
  select * into v_state from public.anonymous_identity_device_state where anonymous_identity_id=p_identity_id for update;
  if v_state.anonymous_identity_id is null then
    insert into public.anonymous_identity_device_state(anonymous_identity_id,active_auth_user_id,generation) values(p_identity_id,p_new_auth_user_id,1) returning * into v_state;
  else
    update public.anonymous_identity_device_state set active_auth_user_id=p_new_auth_user_id,generation=generation+1,updated_at=timezone('utc'::text,now()) where anonymous_identity_id=p_identity_id returning * into v_state;
  end if;
  insert into public.anonymous_identity_binding_history(anonymous_identity_id,active_auth_user_id,generation)
  values(v_state.anonymous_identity_id,v_state.active_auth_user_id,v_state.generation);
  return query select v_state.anonymous_identity_id,v_state.active_auth_user_id,v_state.generation;
end; $$;
revoke all on function public.claim_anonymous_identity_device(uuid,uuid) from public,anon,authenticated;
grant execute on function public.claim_anonymous_identity_device(uuid,uuid) to service_role;

create or replace function public.station_mail_admin_identity_candidates(p_thread_id uuid)
returns table(identity_id uuid, anonymous_display_name text, source text, chat_count bigint, message_count bigint, contact_count bigint, confidence text)
language plpgsql stable security definer set search_path='public'
as $$
begin
  if auth.uid() is null or not exists (select 1 from public.admin_users where user_id=auth.uid() and active=true) then raise exception 'not allowed'; end if;
  if not exists (select 1 from public.station_mail_threads where id=p_thread_id and deleted_at is null) then raise exception 'MAIL_THREAD_NOT_FOUND'; end if;
  return query
  with thread_user as (select user_id from public.station_mail_threads where id=p_thread_id), candidates as (
    select h.anonymous_identity_id, '帳號綁定歷史'::text, 1 from public.anonymous_identity_binding_history h join thread_user tu on tu.user_id=h.active_auth_user_id
    union select tu.user_id, '目前登入匿名身分', 2 from thread_user tu
    union select s.anonymous_identity_id, '裝置綁定紀錄', 3 from public.anonymous_identity_device_state s join thread_user tu on tu.user_id=s.active_auth_user_id
    union select c.anonymous_identity_id, '恢復碼歷史', 4 from public.anonymous_recovery_credentials c join public.anonymous_identity_binding_history h on h.anonymous_identity_id=c.anonymous_identity_id join thread_user tu on tu.user_id=h.active_auth_user_id
    union select a.requester_id, '恢復嘗試紀錄', 5 from public.anonymous_recovery_attempts a join thread_user tu on tu.user_id=a.requester_id
  ), unique_candidates as (select anonymous_identity_id, min(source) source, min(ordinal) ordinal from candidates group by anonymous_identity_id)
  select u.anonymous_identity_id, p.anonymous_display_name, u.source,
    (select count(*) from public.random_chat_sessions s where s.user_a=u.anonymous_identity_id or s.user_b=u.anonymous_identity_id),
    (select count(*) from public.random_chat_messages m join public.random_chat_sessions s on s.id=m.session_id where s.user_a=u.anonymous_identity_id or s.user_b=u.anonymous_identity_id),
    (select count(*) from public.anonymous_contacts c where c.user_a=u.anonymous_identity_id or c.user_b=u.anonymous_identity_id),
    case when u.ordinal=1 then '高' when u.ordinal<=3 then '中' else '低' end
  from unique_candidates u join public.profiles p on p.id=u.anonymous_identity_id and p.anonymous_mode_enabled=true
  order by u.ordinal, p.created_at desc;
end; $$;
revoke all on function public.station_mail_admin_identity_candidates(uuid) from public,anon;
grant execute on function public.station_mail_admin_identity_candidates(uuid) to authenticated;
commit;
